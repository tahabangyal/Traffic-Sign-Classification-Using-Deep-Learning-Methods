# HOG feature extractor (returns 1D vector)
def extract_hog_feature_gray(img, resize=(128,128)):
    im = cv2.resize(img, resize)
    gray = cv2.cvtColor(im, cv2.COLOR_RGB2GRAY)
    fd, hog_image = hog(gray, orientations=9, pixels_per_cell=(8,8),
                       cells_per_block=(2,2), visualize=True, feature_vector=True)
    return fd

# ORB-based descriptor: produce a fixed-length vector by taking mean of descriptors (if any)
orb = cv2.ORB_create(nfeatures=500)
def extract_orb_feature_gray(img, resize=(128,128), orb=orb, out_dim=256):
    im = cv2.resize(img, resize)
    gray = cv2.cvtColor(im, cv2.COLOR_RGB2GRAY)
    kps, des = orb.detectAndCompute(gray, None)
    if des is None:
        return np.zeros(out_dim, dtype=np.float32)
    # flatten by mean pooling across keypoint descriptors then pad/cut to out_dim
    vec = des.mean(axis=0)
    if len(vec) >= out_dim:
        return vec[:out_dim]
    else:
        res = np.zeros(out_dim, dtype=np.float32)
        res[:len(vec)] = vec
        return res

