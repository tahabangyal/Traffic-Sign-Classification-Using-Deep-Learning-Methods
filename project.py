# === 3) MODULE 1: Preprocessing helpers (noise, denoise, geometric transforms, edges) ===
def add_gaussian_noise(img, mean=0, sigma=20):
    gauss = np.random.normal(mean, sigma, img.shape).astype(np.float32)
    noised = img.astype(np.float32) + gauss
    noised = np.clip(noised, 0, 255).astype(np.uint8)
    return noised

def denoise_nlmeans(img):
    # expects uint8 BGR or RGB
    if img.ndim == 3:
        return cv2.fastNlMeansDenoisingColored(img, None, h=10, hColor=10, templateWindowSize=7, searchWindowSize=21)
    else:
        return cv2.fastNlMeansDenoising(img, None, 10, 7, 21)

def rotate_image(img, angle):
    h, w = img.shape[:2]
    M = cv2.getRotationMatrix2D((w/2,h/2), angle, 1.0)
    return cv2.warpAffine(img, M, (w,h))

def show_preprocessing_examples(img_path):
    img = cv2.imread(img_path)
    img_rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    noisy = add_gaussian_noise(img_rgb)
    denoised = denoise_nlmeans(noisy)
    gray = cv2.cvtColor(img_rgb, cv2.COLOR_RGB2GRAY)
    edges = cv2.Canny(gray, 80, 150)
    rot = rotate_image(img_rgb, 25)

